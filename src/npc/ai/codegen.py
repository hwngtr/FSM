"""Single-source-of-truth code generator for browser config, Mermaid diagrams, and TLA+ spec."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from npc.ai.bt import ActionNode, Condition, Node, ReactiveSelector, Selector, Sequence, make_guard_bt
from npc.ai.fsm import FSM_TABLE, Rule, State
from npc.ai.profiles import DEFAULT_PATROL_ROUTE, DEFAULT_PROFILE, PROFILES, GuardProfile
from npc.formal.net import render_tla_module


def build_web_config_dict(
    rules: tuple[Rule, ...] = FSM_TABLE,
    profiles: dict[str, GuardProfile] = PROFILES,
    default_profile: str = DEFAULT_PROFILE.id,
) -> dict[str, Any]:
    """Build the canonical dictionary exported to `web/js/guard_config.js`."""
    return {
        "fsmTable": [
            {"src": r.src.value, "dst": r.dst.value, "guard": r.guard}
            for r in rules
        ],
        "states": [s.value for s in State],
        "defaultProfile": default_profile,
        "profiles": {k: v.to_dict() for k, v in profiles.items()},
        "patrolRoute": [[wp.x, wp.y] for wp in DEFAULT_PATROL_ROUTE],
    }


def render_web_config_js(
    rules: tuple[Rule, ...] = FSM_TABLE,
    profiles: dict[str, GuardProfile] = PROFILES,
) -> str:
    """Render `web/js/guard_config.js` as a deterministic JS bundle."""
    payload = build_web_config_dict(rules=rules, profiles=profiles)
    formatted = json.dumps(payload, indent=2, sort_keys=False)
    return (
        "// AUTO-GENERATED by src/npc/ai/codegen.py from FSM_TABLE and PROFILES.\n"
        "// Do not edit by hand; run `/usr/bin/python3 tools/codegen.py`.\n"
        f"window.GUARD_CONFIG = {formatted};\n"
    )


def render_fsm_mermaid(rules: tuple[Rule, ...] = FSM_TABLE) -> str:
    """Generate a Mermaid `stateDiagram-v2` directly from `FSM_TABLE`."""
    lines: list[str] = [
        "stateDiagram-v2",
        "    direction LR",
        "    [*] --> idle",
    ]
    for r in rules:
        lines.append(f"    {r.src.value} --> {r.dst.value} : {r.guard}")
    return "\n".join(lines) + "\n"


def render_bt_mermaid(root: Node | None = None) -> str:
    """Walk the live Behavior Tree object graph and emit a Mermaid `flowchart TD`."""
    tree = root or make_guard_bt()
    lines: list[str] = ["flowchart TD"]
    counter = 0

    def walk(node: Node, parent_id: str | None, priority_idx: int | None = None) -> str:
        nonlocal counter
        counter += 1
        node_id = f"n{counter}_{node.name}"
        if isinstance(node, ReactiveSelector):
            label = f'"? ReactiveSelector\\n{node.name}"'
            shape = f"{node_id}{{{label}}}"
        elif isinstance(node, Selector):
            label = f'"? Selector\\n{node.name}"'
            shape = f"{node_id}{{{label}}}"
        elif isinstance(node, Sequence):
            p_tag = f" [P{priority_idx}]" if priority_idx is not None else ""
            label = f'"-> Sequence{p_tag}\\n{node.name}"'
            shape = f"{node_id}[{label}]"
        elif isinstance(node, Condition):
            label = f'"Cond: {node.name}"'
            shape = f"{node_id}([{label}])"
        elif isinstance(node, ActionNode):
            label = f'"Act: {node.name}"'
            shape = f"{node_id}[/{label}/]"
        else:
            shape = f'{node_id}["{node.name}"]'

        lines.append(f"    {shape}")
        if parent_id is not None:
            lines.append(f"    {parent_id} --> {node_id}")

        children = getattr(node, "children", ())
        for idx, child in enumerate(children, start=1):
            walk(child, node_id, priority_idx=idx if isinstance(node, ReactiveSelector) else None)
        return node_id

    walk(tree, None)
    return "\n".join(lines) + "\n"


def render_petri_mermaid(rules: tuple[Rule, ...] = FSM_TABLE) -> str:
    """Generate a Mermaid `flowchart LR` of the 1-token Place/Transition Petri net."""
    lines: list[str] = ["flowchart LR"]
    for s in State:
        token = " (● 1)" if s == State.PATROL else ""
        lines.append(f'    p_{s.value}(("p_{s.value}{token}"))')
    for idx, r in enumerate(rules):
        tid = f"t{idx}"
        lines.append(f'    {tid}["{tid}: {r.guard}"]')
        lines.append(f"    p_{r.src.value} --> {tid}")
        lines.append(f"    {tid} --> p_{r.dst.value}")
    return "\n".join(lines) + "\n"


def write_all_artifacts(repo_root: Path) -> list[Path]:
    """Write all derived artifacts (JS config, TLA+ module, Mermaid `.mmd` files)."""
    written: list[Path] = []

    js_path = repo_root / "web" / "js" / "guard_config.js"
    js_path.write_text(render_web_config_js(), encoding="utf-8")
    written.append(js_path)

    tla_path = repo_root / "src" / "npc" / "formal" / "tla" / "Guard.tla"
    tla_path.parent.mkdir(parents=True, exist_ok=True)
    tla_path.write_text(render_tla_module(FSM_TABLE), encoding="utf-8")
    written.append(tla_path)

    diag_dir = repo_root / "docs" / "diagrams"
    diag_dir.mkdir(parents=True, exist_ok=True)

    fsm_mmd = diag_dir / "fsm.mmd"
    fsm_mmd.write_text(render_fsm_mermaid(FSM_TABLE), encoding="utf-8")
    written.append(fsm_mmd)

    bt_mmd = diag_dir / "bt.mmd"
    bt_mmd.write_text(render_bt_mermaid(), encoding="utf-8")
    written.append(bt_mmd)

    petri_mmd = diag_dir / "petri.mmd"
    petri_mmd.write_text(render_petri_mermaid(FSM_TABLE), encoding="utf-8")
    written.append(petri_mmd)

    return written
